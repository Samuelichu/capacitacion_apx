package ch01_java_building_blocks.day_three._01_understanding_java_operators._03_using_additional_binary_operators._04_relational_operators;

public class Operators {
    public static void main (String[] args){
        int x = 10, y = 20, z = 10;

        System.out.println(x < y);  // output: true
        System.out.println(x <= y); // output: true
        System.out.println(x >= z); // output: true
        System.out.println(x > z);  // output: false
    }
}
